// Bundle the CLI into skills/answer-me-with-html/scripts/am-bundle.mjs, and write scripts/am.mjs, the small entry that runs it.
// The bundle ships with the skill directory: after npx skills add / a plugin-marketplace install it runs with Node alone, no npm install.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { inlineAssets } from './inline-assets.mjs';

// Temml is 470 KB of source and only a draft with math runs it, but Node compiles all the code of the bundle on every start (am --version too).
// So the bundle carries Temml's minified build as a string and compiles it on the first `import('temml')`: a render without math does not pay for it.
const temmlAsString = {
  name: 'temml-as-string',
  setup(b) {
    b.onResolve({ filter: /^temml$/ }, () => ({ path: 'temml', namespace: 'temml-string' }));
    b.onLoad({ filter: /.*/, namespace: 'temml-string' }, () => {
      const min = readFileSync(createRequire(import.meta.url).resolve('temml/dist/temml.min.js'), 'utf8');
      return {
        loader: 'js',
        contents: `import { runInThisContext } from 'node:vm';
export default runInThisContext(${JSON.stringify(`(function () {\n${min}\nreturn temml;\n})()`)});\n`,
      };
    });
  },
};

await build({
  entryPoints: [fileURLToPath(new URL('../bin/am.js', import.meta.url))],
  outfile: fileURLToPath(new URL('../skills/answer-me-with-html/scripts/am-bundle.mjs', import.meta.url)),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'eof',
  banner: { js: '// answer-me-with-html CLI — generated by scripts/build.mjs, do not edit. Source: https://github.com/QingYunA/answer-me-with-html' },
  plugins: [inlineAssets, temmlAsString],
  logLevel: 'info',
});

// The entry the skill runs. Node compiles all of the bundle's ~1 MB on every start (about 20 ms of a 100 ms render); from Node 22.1
// it can keep the compiled code on disk instead. The cache only covers modules loaded after it is turned on, so the entry is a separate
// file that turns it on and then loads the bundle. Older Node, a read-only temp folder or NODE_DISABLE_COMPILE_CACHE: the bundle is
// compiled as before.
writeFileSync(fileURLToPath(new URL('../skills/answer-me-with-html/scripts/am.mjs', import.meta.url)), `#!/usr/bin/env node
// answer-me-with-html CLI — generated by scripts/build.mjs, do not edit. Source: https://github.com/QingYunA/answer-me-with-html
// Turns on Node's compile cache, then runs the bundle (am-bundle.mjs, next to this file).
import module from 'node:module';

try {
  module.enableCompileCache?.();
} catch {
  // No cache: the bundle is compiled as usual.
}
await import('./am-bundle.mjs');
`);
